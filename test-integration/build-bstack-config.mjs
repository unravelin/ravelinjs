import { exec } from 'child_process';
import * as fs from 'fs';
import path from 'path';
import { stringify } from 'yaml';

export async function buildBrowserStackConfig() {
  console.log('Building BrowserStack config…');

  // buildName is static, and cannot contain numbers or dates
  const buildName = `${process.env.E2E_RSA_KEY ? 'auto-' : ''}integration-tests`;
  // buildIdentifier is dynamic, we can use Git and Cloud Build to create a unique name
  const buildIdentifier = await generateBuildId();

  const config = {
    projectName: 'ravelinjs',
    buildName,
    buildIdentifier,
    debug: true,
    consoleLogs: 'verbose',
    networkLogs: true,
    parallelsPerPlatform: 1,
    browserstackLocal: true,
    browserStackLocalOptions: {
      localProxyHost: 'localhost',
      localProxyPort: 3000,
    },
    platforms: [
      {
        os: 'Windows',
        osVersion: 10,
        browserName: 'Chrome',
        browserVersion: 'latest',
      },
      {
        os: 'Windows',
        osVersion: 10,
        browserName: 'IE',
        browserVersion: '11.0',
        // https://browserstack.com/docs/automate/selenium/using-sendkeys-on-remote-IE11
        ie: { sendKeys: true },
      },
      {
        os: 'OS X',
        osVersion: 'Sequoia',
        browserName: 'Safari',
        browserVersion: '18.4',
      },
    ],
  };

  // Generate the YAML configuration for BrowserStack
  const str = stringify(config);
  const yaml = `# This file is generated by build-bstack-config.mjs\n${str}`;

  // Write file to root folder for BrowserStack SDK to pick up
  const filePath = path.join(import.meta.dirname, '../browserstack.yml');
  fs.writeFileSync(filePath, yaml, 'utf8');

  console.log(`BrowserStack config written to ${filePath}`);
}

/**
 * Returns an identifier for the build in question.
 * @returns {String}
 */
async function generateBuildId() {
  if (process.env.HEAD_BRANCH) {
    const trigger = process.env.E2E_RSA_KEY ? 'e2e' : 'ci';

    // Example: "ci/main/abc-1234/def-5678"
    return `${trigger}/${process.env.HEAD_BRANCH}/${process.env.COMMIT_SHA.substring(0, 7)}/${
      process.env.BUILD_ID
    }`;
  }

  return await gitBuildId();
}

/**
 * Returns a description of the git revision of the working directory.
 * @returns {Promise}
 */
function gitBuildId() {
  return new Promise(function (resolve, reject) {
    exec('git describe --all --long --dirty', function (err, stdout, stderr) {
      if (err) {
        reject('git describe: ' + err + ' stderr: ' + stderr);
        return;
      }
      resolve(stdout.trim());
    });
  });
}

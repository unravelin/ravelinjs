import { execSync } from 'child_process';
import * as fs from 'fs';
import path from 'path';
import { stringify } from 'yaml';

export function buildBrowserStackConfig() {
  console.log('Building BrowserStack config…');

  const gitBranch = generateBuildName();
  const buildId = generateBuildId();

  const config = {
    projectName: 'ravelinjs',
    buildName: gitBranch,
    buildIdentifier: buildId,
    buildTag: gitBranch,
    debug: true,
    consoleLogs: 'verbose',
    networkLogs: true,
    parallelsPerPlatform: 1,
    // Allow HTTPS connections with our self-signed cert
    acceptInsecureCerts: true,
    browserstackLocal: true,
    browserStackLocalOptions: {
      localProxyHost: 'localhost',
      localProxyPort: 3000,
    },
    platforms: generatePlatforms(),
  };

  // Generate the YAML configuration for BrowserStack
  const str = stringify(config);
  const yaml = `# This file is generated by build-bstack-config.mjs\n${str}`;

  // Write file to root folder for BrowserStack SDK to pick up
  const filePath = path.join(import.meta.dirname, '../browserstack.yml');
  fs.writeFileSync(filePath, yaml, 'utf8');

  console.log(`BrowserStack config written to ${filePath}`);
}

/**
 * @returns {String}
 */
function generateBuildName() {
  if (process.env.E2E_RSA_KEY) {
    return 'auto-integration-tests';
  }
  if (process.env.HEAD_BRANCH) {
    return process.env.HEAD_BRANCH;
  }
  return gitBranch();
}

/**
 * @returns {String}
 */
function generateBuildId() {
  if (process.env.HEAD_BRANCH) {
    const trigger = process.env.E2E_RSA_KEY ? 'e2e' : 'ci';

    // Example: "ci/main/abc-1234/def-5678"
    return `${trigger}/${process.env.HEAD_BRANCH}/${process.env.COMMIT_SHA.substring(0, 7)}/${
      process.env.BUILD_ID
    }`;
  }

  return gitBuildId();
}

/**
 * Returns a description of the git revision of the working directory.
 * @returns {String}
 */
function gitBuildId() {
  try {
    return execSync('git describe --all --long --dirty', { encoding: 'utf8' }).trim();
  } catch (err) {
    throw new Error('git describe: ' + err.message);
  }
}

/**
 * Returns the current git branch.
 * @returns {String}
 */
function gitBranch() {
  try {
    return execSync('git rev-parse --abbrev-ref HEAD', { encoding: 'utf8' }).trim();
  } catch (err) {
    throw new Error('git rev-parse: ' + err.message);
  }
}

/**
 * Returns a list of platforms to run against.
 * @returns {String[]}
 */
function generatePlatforms() {
  // Chrome on Windows 11
  const singlePlatform = {
    os: 'Windows',
    osVersion: 11,
    browserName: 'Chrome',
    browserVersion: 'latest',
  };

  if (process.argv.includes('--single-platform')) {
    return [singlePlatform];
  }

  return [
    singlePlatform,
    // Firefox on Windows 10
    {
      browserName: 'Firefox',
      os: 'Windows',
      osVersion: 10,
      browserVersion: 'latest',
    },
    // Safari on macOS Sequoia (2024)
    {
      os: 'OS X',
      osVersion: 'Sequoia',
      browserName: 'Safari',
      browserVersion: '18.4',
    },
    // Safari on iOS 17 (2024)
    {
      browserName: 'safari',
      osVersion: 17,
      deviceName: 'iPhone 15',
    },
    // Chrome on Android 13 (2022)
    {
      browserName: 'chrome',
      osVersion: '13.0',
      deviceName: 'Samsung Galaxy S23',
    },
  ];
}
